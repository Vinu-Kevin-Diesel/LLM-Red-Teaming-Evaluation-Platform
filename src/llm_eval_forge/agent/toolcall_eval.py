"""Offline evaluation of the tool-call guard on held-out AgentDojo traces (the banking suite).

    python -m llm_eval_forge.agent.toolcall_eval --model models/toolcall-guard-A
    python -m llm_eval_forge.agent.toolcall_eval --model models/toolcall-guard-A --from-preds   # reuse saved scores
    -> results/metrics_toolcall/<name>.json, results/toolcall_guard_table.md
"""
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

from llm_eval_forge.distill.data import read_split, write_jsonl
from llm_eval_forge.distill.metrics import best_f1_threshold, fit_temperature

DATA = Path("data/toolcalls")
METRICS_DIR = Path("results/metrics_toolcall")


def by_function(rows: list[dict], probs: list[float], threshold: float) -> dict:
    """Per tool: legitimate calls and how many would be blocked, attacker calls and how many are caught."""
    out: dict[str, Counter] = defaultdict(Counter)
    for r, p in zip(rows, probs):
        c = out[r["meta"]["function"]]
        kind = "attack" if r["label"] else "legit"
        c[kind] += 1
        c[f"{kind}_blocked"] += p >= threshold
    return {f: dict(c) for f, c in sorted(out.items(), key=lambda kv: -sum(kv[1].values()))}


def false_blocks_by_task(rows: list[dict], probs: list[float], threshold: float) -> list[dict]:
    blocked = Counter(r["meta"]["user_task"] for r, p in zip(rows, probs) if not r["label"] and p >= threshold)
    goals = {r["meta"]["user_task"]: r["prompt"].split("\n", 1)[0].removeprefix("GOAL: ") for r in rows}
    return [{"user_task": t, "false_blocks": n, "goal": goals[t]} for t, n in blocked.most_common()]


def evaluate(model_dir: str, name: str | None = None, from_preds: bool = False) -> dict:
    from llm_eval_forge.distill.evaluate import set_metrics, student_predictor

    name = name or Path(model_dir).name
    val = read_split(DATA, "val")
    test = read_split(DATA, "test")
    if from_preds:
        saved = {split: {(r := json.loads(line))["id"]: r["p"] for line in
                         (DATA / "preds" / name / f"{split}.jsonl").read_text(encoding="utf-8").splitlines() if line}
                 for split in ("val", "test")}
        p_val, p_test = [saved["val"][r["id"]] for r in val], [saved["test"][r["id"]] for r in test]
    else:
        predict = student_predictor(model_dir)
        p_val, p_test = predict(val), predict(test)
        for split, rows, probs in (("val", val, p_val), ("test", test, p_test)):
            write_jsonl(DATA / "preds" / name / f"{split}.jsonl",
                        ({"id": r["id"], "label": r["label"], "p": p} for r, p in zip(rows, probs)))
    labels_val = [r["label"] for r in val]
    threshold = best_f1_threshold(labels_val, p_val)[0]
    temperature = fit_temperature(labels_val, p_val)
    out = {"name": name, "threshold": threshold, "temperature": round(temperature, 2),
           "val": set_metrics(labels_val, p_val, threshold, temperature),
           "test_banking": set_metrics([r["label"] for r in test], p_test, threshold, temperature),
           "test_by_attack": {}, "test_by_function": by_function(test, p_test, threshold),
           "test_false_blocks_by_task": false_blocks_by_task(test, p_test, threshold)}
    by_attack = defaultdict(list)
    for r, p in zip(test, p_test):
        by_attack[r["meta"].get("attack") or "none"].append((r["label"], p))
    for attack, pairs in sorted(by_attack.items()):
        if sum(y for y, _ in pairs) == 0:
            continue  # clean runs have no attacker calls; covered by the FPR of the overall set
        out["test_by_attack"][attack] = set_metrics([y for y, _ in pairs], [p for _, p in pairs], threshold, temperature)
    METRICS_DIR.mkdir(parents=True, exist_ok=True)
    (METRICS_DIR / f"{name}.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    Path("results/toolcall_guard_table.md").write_text(render(out), encoding="utf-8")
    return out


def render(m: dict) -> str:
    t = m["test_banking"]

    def row(label, s):
        return (f"| {label} | {s['n']:,} | {s['positives']:,} | {100 * s['f1']:.1f} | {100 * s['precision']:.1f} | "
                f"{100 * s['recall']:.1f} | {100 * s['fpr']:.2f} | {100 * (s['auroc'] or 0):.1f} |")

    lines = ["# Tool-call guard: offline evaluation on AgentDojo traces", "",
             f"`{m['name']}` judges each proposed tool call (goal, calls so far, last tool output, proposed call). "
             "Trained on the workspace, travel and slack suites; **banking is held out entirely** (unseen tools and "
             f"data). Threshold {m['threshold']} tuned on validation. Positive = attacker-induced call. FPR = share "
             "of legitimate calls that would be blocked. Generated by `python -m llm_eval_forge.agent.toolcall_eval`.", "",
             "| Set | Calls | Attacker calls | F1 | Precision | Recall | FPR | AUROC |",
             "|---|---:|---:|---:|---:|---:|---:|---:|",
             row("Banking (held-out suite)", t), row("Validation (seen suites, unseen user tasks)", m["val"])]
    for attack, s in m["test_by_attack"].items():
        lines.append(row(f"Banking · {attack}", s))
    fn = m.get("test_by_function")
    if fn:
        lines += ["", "**By tool** (held-out banking). Read-only tools never see an attacker call, so the false blocks "
                      "that matter are on the tools that move money or change settings.", "",
                  "| Tool | Legitimate calls | Falsely blocked | Attacker calls | Caught |", "|---|---:|---:|---:|---:|"]
        for f, c in fn.items():
            legit, attack = c.get("legit", 0), c.get("attack", 0)
            fb = f"{c.get('legit_blocked', 0):,} ({100 * c.get('legit_blocked', 0) / legit:.1f}%)" if legit else "–"
            caught = f"{c.get('attack_blocked', 0):,} ({100 * c.get('attack_blocked', 0) / attack:.1f}%)" if attack else "–"
            lines.append(f"| `{f}` | {legit:,} | {fb} | {attack:,} | {caught} |")
    tasks = m.get("test_false_blocks_by_task")
    if tasks:
        total = sum(t["false_blocks"] for t in tasks)
        top = tasks[0]
        lines += ["", f"False blocks by user task: " + ", ".join(f"{t['user_task']} {t['false_blocks']}" for t in tasks)
                  + f". The top one ({top['false_blocks']} of {total}) is \"{top['goal']}\"."]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate the tool-call guard on held-out AgentDojo traces")
    parser.add_argument("--model", required=True)
    parser.add_argument("--name")
    parser.add_argument("--from-preds", action="store_true", help="Score saved predictions instead of running the model")
    args = parser.parse_args()
    out = evaluate(args.model, args.name, from_preds=args.from_preds)
    print(render(out))


if __name__ == "__main__":
    main()
